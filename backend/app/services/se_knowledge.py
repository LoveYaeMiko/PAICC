_started = False


def _seed_worker() -> None:
    """Ingest any missing SE documents, tolerating a slow/absent vector store."""
    try:
        existing = {str(d.get("title", "") or "") for d in knowledge_base.list_documents()}
        added = 0
        for title, text in SEED_DOCUMENTS:
            if title in existing:
                continue
            try:
                knowledge_base.ingest_text(title, text)
                existing.add(title)
                added += 1
            except Exception:  # noqa: BLE001
                logger.exception("failed to seed knowledge document %s", title)
        if added:
            logger.info("seeded %d software-engineering knowledge documents", added)
    except Exception:  # noqa: BLE001
        logger.exception("software-engineering knowledge seeding failed")


def seed() -> None:
    """Idempotent boot hook — start seeding on a daemon thread (never blocks startup)."""
    global _started
    if _started:
        return
    _started = True
    threading.Thread(target=_seed_worker, daemon=True, name="se-kb-seed").start()
